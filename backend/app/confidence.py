"""Deterministic confidence scoring for extracted financial metrics.

The LLM's self-reported confidence is only one signal.  A score is computed for
every metric from reproducible evidence: snippet grounding, concept/label match,
unit and period consistency, prior-year sanity, and the model's own estimate.
Weights live in :data:`CONFIDENCE_CONFIG` and can be overridden with environment
variables so the audit policy is configurable without code changes.
"""

from __future__ import annotations

import json
import os
import re
from typing import Any

from app.schemas import ExtractedMetric
from app.units import apply_unit_normalization, normalize_metric_dict, parse_unit

__all__ = [
    "CONFIDENCE_CONFIG",
    "CONFIDENCE_WEIGHTS",
    "apply_extractor_agreement",
    "compare_extractor_batches",
    "compute_confidence",
    "label_confidence",
    "metric_role",
    "metric_terms",
]

# Weights sum to 1.0.  Extractor disagreement (0.0) can lower an otherwise
# perfect score to 0.80, below the default 0.85 escalation threshold.
CONFIDENCE_WEIGHTS: dict[str, float] = {
    "snippet_grounding": 0.22,
    "concept_match": 0.10,
    "unit_consistency": 0.08,
    "period_consistency": 0.08,
    "column_period": 0.08,
    "cross_statement": 0.07,
    "prior_year_sanity": 0.07,
    "extractor_agreement": 0.20,
    "llm_confidence": 0.10,
}
DEFAULT_WEIGHTS = CONFIDENCE_WEIGHTS


def _load_weights() -> dict[str, float]:
    weights = dict(DEFAULT_WEIGHTS)
    raw = (os.getenv("CONFIDENCE_WEIGHTS") or "").strip()
    if raw:
        try:
            overrides = json.loads(raw)
        except json.JSONDecodeError:
            overrides = {}
        if isinstance(overrides, dict):
            for key, value in overrides.items():
                if key in weights:
                    try:
                        weights[key] = max(0.0, float(value))
                    except (TypeError, ValueError):
                        continue
    return weights


def _env_float(name: str, default: float) -> float:
    try:
        return float(os.getenv(name, str(default)))
    except ValueError:
        return default


CONFIDENCE_CONFIG: dict[str, Any] = {
    "weights": _load_weights(),
    "high_confidence_threshold": _env_float("CONFIDENCE_HIGH_THRESHOLD", 0.85),
    "prior_ratio_min": _env_float("CONFIDENCE_PRIOR_RATIO_MIN", 0.02),
    "prior_ratio_max": _env_float("CONFIDENCE_PRIOR_RATIO_MAX", 50.0),
}

_KNOWN_ROLES = {
    "Revenue",
    "Net Income",
    "Total Assets",
    "Total Liabilities",
    "Shareholders' Equity",
    "Operating Cash Flow",
    "Cash and Cash Equivalents",
    "R&D / Operating Income",
}

_CONCEPT_TERMS: dict[str, tuple[str, ...]] = {
    "Revenue": ("revenue", "net sales", "sales"),
    "Net Income": ("net income", "net earnings", "net loss"),
    "Total Assets": ("total assets", "assets"),
    "Total Liabilities": ("total liabilities", "liabilities"),
    "Shareholders' Equity": (
        "shareholders' equity",
        "stockholders' equity",
        "total equity",
    ),
    "Operating Cash Flow": (
        "operating activities",
        "operating cash flow",
        "cash from operations",
    ),
    "Cash and Cash Equivalents": ("cash and cash equivalents", "cash equivalents"),
    "R&D / Operating Income": (
        "research and development",
        "r&d",
        "operating income",
    ),
}


def _normalize_name(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", str(name).lower()).strip()


def _value_digits(value: float) -> str:
    text = str(int(value)) if float(value).is_integer() else f"{value:g}"
    return re.sub(r"\D", "", text)


def metric_role(name: str) -> str:
    """Map a metric name to its canonical XBRL comparison role."""
    normalized = _normalize_name(name)
    if "revenue" in normalized or "net sales" in normalized:
        return "Revenue"
    if "net income" in normalized or "net earnings" in normalized or "net loss" in normalized:
        return "Net Income"
    if normalized == "assets" or "total assets" in normalized:
        return "Total Assets"
    if normalized == "liabilities" or "total liabilities" in normalized:
        return "Total Liabilities"
    if (
        "shareholders equity" in normalized
        or "stockholders equity" in normalized
        or normalized == "total equity"
    ):
        return "Shareholders' Equity"
    if (
        "operating cash flow" in normalized
        or "operating activities" in normalized
        or "cash provided by operating" in normalized
        or "cash generated by operating" in normalized
        or "cash from operations" in normalized
    ):
        return "Operating Cash Flow"
    if "cash and cash equivalents" in normalized:
        return "Cash and Cash Equivalents"
    if "research" in normalized and "development" in normalized:
        return "R&D / Operating Income"
    if "operating income" in normalized:
        return "R&D / Operating Income"
    return name


def metric_terms(role: str) -> tuple[str, ...]:
    """Return the label terms used to identify a metric role."""
    return _CONCEPT_TERMS.get(role, ())


def _snippet_grounding(metric: ExtractedMetric) -> float:
    digits = _value_digits(metric.value)
    snippet_digits = re.sub(r"\D", "", metric.source_snippet)
    return 1.0 if digits and digits in snippet_digits else 0.0


def _concept_match(metric: ExtractedMetric) -> float:
    role = metric_role(metric.metric_name)
    if role not in _KNOWN_ROLES:
        return 0.2

    snippet = metric.source_snippet.lower()
    name = metric.metric_name.lower()
    terms = _CONCEPT_TERMS.get(role, ())
    if any(term in snippet for term in terms):
        return 1.0
    if any(term in name for term in terms):
        return 0.75
    return 0.5


def _unit_consistency(metric: ExtractedMetric) -> float:
    scale = parse_unit(metric.unit)
    return 1.0 if scale.recognized else 0.0


def _period_years(text: str) -> set[str]:
    return set(re.findall(r"(?:19|20)\d{2}", str(text or "")))


def _period_consistency(metric: ExtractedMetric, metadata: dict[str, Any]) -> float:
    expected_years = _period_years(str(metadata.get("fiscal_year") or ""))
    expected_years |= _period_years(str(metadata.get("report_date") or ""))
    actual_years = _period_years(metric.period)

    if not expected_years:
        return 0.7 if actual_years else 0.4
    if actual_years and actual_years & expected_years:
        return 1.0
    return 0.2


def _prior_year_sanity(metric: ExtractedMetric) -> float:
    prior = metric.prior_year_value
    if prior is None:
        return 0.6
    if prior == 0:
        return 1.0 if metric.value == 0 else 0.3

    # A sign flip can be legitimate (loss to profit), but it deserves a mild
    # penalty rather than being treated as a hard failure.
    if metric.value == 0:
        return 0.8
    if metric.value * prior < 0:
        return 0.5

    ratio = abs(metric.value / prior)
    if CONFIDENCE_CONFIG["prior_ratio_min"] <= ratio <= CONFIDENCE_CONFIG["prior_ratio_max"]:
        return 1.0
    return 0.4


def _column_period_signal(metric: ExtractedMetric) -> float:
    """Return whether the value sits in the filing's current-period column."""
    if metric.period_column_matched is None:
        return 0.5
    return 1.0 if metric.period_column_matched else 0.0


def _cross_statement_signal(metric: ExtractedMetric) -> float:
    """Return the Net Income cash-flow cross-statement signal.

    The check only applies to Net Income.  When no cash-flow opening line is
    available the signal stays neutral rather than penalizing the metric.
    """
    if metric_role(metric.metric_name) != "Net Income":
        return 1.0
    if metric.cross_statement_match is None:
        return 1.0
    return 1.0 if metric.cross_statement_match else 0.0


def _extractor_agreement_signal(metric: ExtractedMetric) -> float:
    status = metric.extractor_agreement or "fallback-unavailable"
    if status == "agree":
        return 1.0
    if status == "disagree":
        return 0.0
    return 0.5


def _batch_metrics(batch: Any) -> list[Any]:
    if batch is None:
        return []
    metrics = getattr(batch, "metrics", None)
    if metrics is None and isinstance(batch, dict):
        metrics = batch.get("metrics")
    return list(metrics or [])


def _metric_dict(metric: Any) -> dict[str, Any]:
    if hasattr(metric, "model_dump"):
        return metric.model_dump(mode="json")
    if isinstance(metric, dict):
        return dict(metric)
    return {}


def _normalized_usd(metric: Any) -> float | None:
    data = normalize_metric_dict(_metric_dict(metric))
    value = data.get("value_usd")
    return float(value) if value is not None else None


def compare_extractor_batches(
    primary: Any,
    fallback: Any,
    *,
    primary_error: str | None = None,
    fallback_error: str | None = None,
    tolerance_pct: float = 0.5,
) -> dict[str, dict[str, Any]]:
    """Compare primary and fallback extractions by canonical metric role.

    Values are normalized to full USD before comparison.  The result keyed by
    role contains a status in ``agree`` / ``disagree`` /
    ``fallback-unavailable`` and the values used for the comparison.
    """
    primary_by_role: dict[str, Any] = {}
    fallback_by_role: dict[str, Any] = {}
    for metric in _batch_metrics(primary):
        role = metric_role(_metric_dict(metric).get("metric_name", ""))
        primary_by_role.setdefault(role, metric)
    for metric in _batch_metrics(fallback):
        role = metric_role(_metric_dict(metric).get("metric_name", ""))
        fallback_by_role.setdefault(role, metric)

    roles = sorted(set(primary_by_role) | set(fallback_by_role))
    comparison: dict[str, dict[str, Any]] = {}
    for role in roles:
        primary_metric = primary_by_role.get(role)
        fallback_metric = fallback_by_role.get(role)
        primary_usd = _normalized_usd(primary_metric) if primary_metric else None
        fallback_usd = _normalized_usd(fallback_metric) if fallback_metric else None
        details: dict[str, Any] = {
            "primary_value_usd": primary_usd,
            "fallback_value_usd": fallback_usd,
            "tolerance_pct": tolerance_pct,
            "primary_error": primary_error,
            "fallback_error": fallback_error,
        }
        if primary_usd is None or fallback_usd is None:
            comparison[role] = {
                "status": "fallback-unavailable",
                "details": details,
            }
            continue
        denominator = max(abs(primary_usd), abs(fallback_usd), 1e-9)
        difference_pct = abs(primary_usd - fallback_usd) / denominator * 100.0
        details["difference_pct"] = round(difference_pct, 6)
        comparison[role] = {
            "status": "agree" if difference_pct <= tolerance_pct else "disagree",
            "details": details,
        }
    return comparison


def apply_extractor_agreement(
    metrics: list[ExtractedMetric],
    agreement: dict[str, dict[str, Any]] | None,
) -> None:
    """Copy per-role agreement results onto the selected extraction."""
    for metric in metrics:
        role = metric_role(metric.metric_name)
        result = (agreement or {}).get(role) or {
            "status": "fallback-unavailable",
            "details": {
                "primary_value_usd": None,
                "fallback_value_usd": None,
                "tolerance_pct": 0.5,
            },
        }
        status = str(result.get("status") or "fallback-unavailable")
        if status not in {"agree", "disagree", "fallback-unavailable"}:
            status = "fallback-unavailable"
        metric.extractor_agreement = status  # type: ignore[assignment]
        metric.extractor_agreement_details = dict(result.get("details") or {})


def label_confidence(score: float, threshold: float | None = None) -> str:
    """Return ``HIGH`` or ``LOW`` for a score and configurable threshold."""
    cutoff = (
        CONFIDENCE_CONFIG["high_confidence_threshold"]
        if threshold is None
        else float(threshold)
    )
    return "HIGH" if float(score) >= cutoff else "LOW"


def compute_confidence(
    metric: ExtractedMetric,
    *,
    filing_metadata: dict[str, Any] | None = None,
    threshold: float | None = None,
) -> dict[str, Any]:
    """Compute and store the deterministic confidence score for one metric.

    Returns a dictionary with ``score``, ``label`` and ``signals`` so callers can
    persist or display the breakdown.
    """
    apply_unit_normalization(metric)
    metadata = filing_metadata or {}

    signals: dict[str, float] = {
        "snippet_grounding": _snippet_grounding(metric),
        "concept_match": _concept_match(metric),
        "unit_consistency": _unit_consistency(metric),
        "period_consistency": _period_consistency(metric, metadata),
        "column_period": _column_period_signal(metric),
        "cross_statement": _cross_statement_signal(metric),
        "prior_year_sanity": _prior_year_sanity(metric),
        "extractor_agreement": _extractor_agreement_signal(metric),
        "llm_confidence": max(0.0, min(float(metric.confidence), 1.0)),
    }
    weights = CONFIDENCE_CONFIG["weights"]
    total_weight = sum(weights.values()) or 1.0
    score = sum(signals[key] * weights.get(key, 0.0) for key in signals) / total_weight
    score = round(max(0.0, min(score, 1.0)), 4)
    label = label_confidence(score, threshold)

    metric.confidence_score = score
    metric.confidence_signals = {key: round(value, 4) for key, value in signals.items()}
    metric.confidence_label = label  # type: ignore[assignment]
    return {
        "score": score,
        "label": label,
        "signals": metric.confidence_signals,
        "extractor_agreement": metric.extractor_agreement or "fallback-unavailable",
    }
