"""Strict Pydantic models shared by the PS-01 filing auditor."""

from __future__ import annotations

import re
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

__all__ = [
    "ExtractedMetric",
    "ExtractionBatch",
    "LLMExtractedMetric",
    "LLMExtractionBatch",
    "ValidationCheck",
]


class ExtractedMetric(BaseModel):
    """One financial metric extracted from a 10-K table."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    metric_name: str = Field(min_length=1)
    value: float
    prior_year_value: float | None = None
    unit: str = Field(min_length=1, description='Reporting unit, e.g. "USD Millions".')
    period: str = Field(min_length=1, description='Fiscal period, e.g. "FY2025".')
    source_snippet: str = Field(min_length=1, description="Exact source table row text.")
    confidence: float = Field(ge=0.0, le=1.0)

    # Deterministic confidence scoring (3.3)
    confidence_score: float | None = Field(default=None, ge=0.0, le=1.0)
    confidence_signals: dict[str, float] = Field(default_factory=dict)
    confidence_label: Literal["HIGH", "LOW"] | None = None

    # Multi-extractor agreement.  ``fallback-unavailable`` means the two
    # providers could not be compared; it is less risky than disagreement but
    # still leaves an evidence gap.
    extractor_agreement: Literal["agree", "disagree", "fallback-unavailable"] | None = None
    extractor_agreement_details: dict[str, Any] = Field(default_factory=dict)

    # Unit normalization (task 4).  ``value`` and ``unit`` stay exactly as
    # extracted; the USD fields are used by the validator and XBRL comparison.
    original_value: float | None = None
    unit_scale: float | None = Field(default=None, gt=0.0)
    normalized_unit: str = "USD"
    value_usd: float | None = None
    prior_year_value_usd: float | None = None

    # Evidence context reconstructed from the parsed filing tables.
    source_table_index: int | None = None
    source_table_title: str | None = None
    source_table_category: str | None = None
    source_header: list[str] = Field(default_factory=list)
    source_row: list[str] = Field(default_factory=list)
    source_row_text: str | None = None
    value_column_index: int | None = None
    value_column_header: str | None = None
    period_column_matched: bool | None = None
    cross_statement_match: bool | None = None
    cross_statement_note: str | None = None

    @field_validator("value", "prior_year_value", mode="before")
    @classmethod
    def _parse_numeric_text(cls, raw: object) -> object:
        """Accept ``$1,234``, ``(1,234)`` and similar LLM output."""
        if raw is None:
            return None
        if not isinstance(raw, str):
            return raw

        text = raw.strip()
        negative = text.startswith("(") and text.endswith(")")
        text = text.strip("()").replace("$", "").replace(",", "").strip()
        if not text:
            return raw
        try:
            number = float(text)
        except ValueError:
            return raw
        return -number if negative else number


class ExtractionBatch(BaseModel):
    """The complete set of metrics extracted from one filing."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    company_name: str = Field(min_length=1)
    cik: str = Field(pattern=r"^\d{10}$")
    metrics: list[ExtractedMetric] = Field(min_length=8)

    @field_validator("cik", mode="before")
    @classmethod
    def _normalize_cik(cls, raw: object) -> object:
        if isinstance(raw, str):
            digits = re.sub(r"\D", "", raw)
            if digits:
                return digits.zfill(10)
        return raw

    @model_validator(mode="after")
    def _require_metric_coverage(self) -> "ExtractionBatch":
        names = [metric.metric_name.lower() for metric in self.metrics]

        def has(*needles: str) -> bool:
            return any(all(needle in name for needle in needles) for name in names)

        checks = {
            "Revenue": has("revenue") or has("net sales"),
            "Net Income": has("net income") or has("net earnings") or has("net loss"),
            "Total Assets": has("total assets") or "assets" in names,
            "Total Liabilities": has("total liabilities") or "liabilities" in names,
            "Shareholders' Equity": has("equity"),
            "Operating Cash Flow": (
                has("operating cash flow")
                or has("operating activities")
                or has("cash provided by operating")
                or has("cash generated by operating")
                or has("cash from operations")
            ),
            "Cash and Cash Equivalents": has("cash and cash equivalents"),
            "R&D or Operating Income": has("research", "development") or has("operating income"),
        }
        missing = [role for role, present in checks.items() if not present]
        if missing:
            raise ValueError(
                "ExtractionBatch is missing required metrics: " + ", ".join(missing)
            )
        return self


class LLMExtractedMetric(BaseModel):
    """Provider-facing subset of :class:`ExtractedMetric`.

    Gemini and Groq both reject JSON schemas containing free-form objects such
    as ``dict[str, Any]`` (Groq requires ``additionalProperties: false`` on
    every object).  Only the fields the model must actually fill are exposed
    here; the deterministic enrichment fields stay on ``ExtractedMetric`` and
    are populated by Python after extraction.
    """

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    metric_name: str = Field(min_length=1)
    value: float
    prior_year_value: float | None = None
    unit: str = Field(min_length=1, description='Reporting unit, e.g. "USD Millions".')
    period: str = Field(min_length=1, description='Fiscal period, e.g. "FY2025".')
    source_snippet: str = Field(min_length=1, description="Exact source table row text.")
    confidence: float = Field(ge=0.0, le=1.0)


class LLMExtractionBatch(BaseModel):
    """Provider-facing subset of :class:`ExtractionBatch`."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    company_name: str = Field(min_length=1)
    cik: str = Field(min_length=1)
    metrics: list[LLMExtractedMetric]


class ValidationCheck(BaseModel):
    """Result of one deterministic validation rule."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    rule_name: str = Field(min_length=1)
    metric_name: str = Field(min_length=1)
    passed: bool
    severity: Literal["PASS", "WARNING", "FAIL", "SKIPPED"]
    reason: str = Field(min_length=1)
    status: Literal["PASSED", "FAILED", "SKIPPED"] = "FAILED"
    details: dict[str, Any] = Field(default_factory=dict)
    metrics_involved: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _sync_status(self) -> "ValidationCheck":
        if self.severity == "SKIPPED":
            if self.passed:
                raise ValueError("A skipped check cannot be marked passed.")
            self.status = "SKIPPED"
        elif self.passed:
            if self.severity != "PASS":
                raise ValueError("A passing check must have severity PASS.")
            self.status = "PASSED"
        else:
            if self.severity == "PASS":
                raise ValueError("A non-passing check cannot have severity PASS.")
            self.status = "FAILED"
        if not self.metrics_involved:
            self.metrics_involved = [self.metric_name]
        return self

