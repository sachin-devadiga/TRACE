def get_checkpoint_path() -> Path:
    """Return the configured LangGraph checkpoint database path."""
    return store_get_checkpoint_path()


def build_checkpointer(
    checkpoint_path: Path | str | None = None,
) -> tuple[Any, Any]:
    """Open the persistent checkpoint store and return its connection and saver.

    MongoDB is used when ``MONGO_URI`` is set; otherwise the local SQLite
    checkpoint file is used.  The first return value is the object that must be
    closed on shutdown (a SQLite connection, or the Mongo saver).
    """
    if using_mongodb():
        return _build_mongo_checkpointer()
    path = (
        Path(checkpoint_path).expanduser().resolve()
        if checkpoint_path
        else get_checkpoint_path()
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    initialize_database()
    connection = sqlite3.connect(
        str(path),
        check_same_thread=False,
        timeout=30.0,
    )
    saver = SqliteSaver(connection)
    saver.setup()
    return connection, saver


def _build_mongo_checkpointer() -> tuple[Any, Any]:
    """Return a LangGraph checkpoint saver backed by MongoDB."""
    from langgraph.checkpoint.mongodb import MongoDBSaver

    from app.mongo_client import get_client, mongo_db_name

    client = get_client()
    database = client[mongo_db_name()]

    # MongoDBSaver.from_conn_string creates this compound index; we build the
    # saver directly so we can keep one long-lived client for the process.
    for collection_name in ("checkpoints", "checkpoint_writes"):
        database[collection_name].create_index(
            [("thread_id", 1), ("checkpoint_ns", 1), ("checkpoint_id", -1)],
            unique=True,
        )

    saver = MongoDBSaver(
        client,
        db_name=mongo_db_name(),
        checkpoint_collection_name="checkpoints",
        writes_collection_name="checkpoint_writes",
    )
    return saver, saver


def build_audit_graph(
    checkpointer: SqliteSaver | None = None,
    checkpoint_path: Path | str | None = None,
):
    """Compile the five-node audit workflow.

    If ``checkpointer`` is omitted, a new SQLite-backed saver is created.  The
    caller should normally create the saver with :func:`build_checkpointer` so
    that the underlying connection can be closed at shutdown.
    """
    if checkpointer is None:
        _, checkpointer = build_checkpointer(checkpoint_path)

    builder = StateGraph(AuditState)
    builder.add_node("fetch_node", fetch_node)
    builder.add_node("extract_node", extract_node)
    builder.add_node("validate_node", validate_node)
    builder.add_node("human_review_node", human_review_node)
    builder.add_node("finalize_node", finalize_node)

    builder.add_edge(START, "fetch_node")
    builder.add_edge("fetch_node", "extract_node")
    builder.add_edge("extract_node", "validate_node")
    builder.add_edge("validate_node", "human_review_node")
    builder.add_edge("human_review_node", "finalize_node")
    builder.add_edge("finalize_node", END)

    return builder.compile(checkpointer=checkpointer)
