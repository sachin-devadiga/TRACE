def fetch_node(state: AuditState) -> dict[str, Any]:
    """Fetch the latest 10-K tables from SEC EDGAR.

    The checkpoint normally prevents this node from running twice, but the
    guard below also protects callers that invoke the node directly.
    """
    if state.get("tables_markdown"):
        return {}

    cik = str(state.get("cik") or "").strip()
    if not cik:
        raise ValueError("AuditState.cik is required.")

    filing = fetch_latest_10k_tables(cik)
    tables = filing.get("tables") or []
    if not tables:
        raise RuntimeError(f"No financial tables returned for CIK {cik}.")

    metadata = {
        "company_name": filing.get("company_name", ""),
        "cik": filing.get("cik", cik),
        "accession_number": filing.get("accession_number"),
        "filing_date": filing.get("filing_date"),
        "report_date": filing.get("report_date"),
        "fiscal_year": filing.get("fiscal_year"),
        "primary_document": filing.get("primary_document"),
        "filing_url": filing.get("filing_url"),
    }
    return {
        "company_name": filing.get("company_name") or state.get("company_name") or "",
        "tables_markdown": tables,
        "filing_metadata": metadata,
        "status": "FETCHED",
    }


def extract_node(state: AuditState) -> dict[str, Any]:
    """Extract the eight required metrics with Gemini/Groq fallback."""
    if state.get("extracted_metrics"):
        return {}

    if not state.get("tables_markdown"):
        raise ValueError("tables_markdown is empty; fetch_node must run first.")

    prompt = _build_extraction_prompt(state)
    wire_batch, agreement = extract_with_agreement(prompt, LLMExtractionBatch)
    batch = ExtractionBatch.model_validate(wire_batch.model_dump())

    # 3.2 requires at least eight metrics per filing.  Enforce the required
    # roles deterministically rather than trusting the model to comply.
    found_roles = {metric_role(metric.metric_name) for metric in batch.metrics}
    missing_roles = [
        name for name in REQUIRED_METRICS if metric_role(name) not in found_roles
    ]
    if len(batch.metrics) < 8 or missing_roles:
        raise ValueError(
            "Extraction returned "
            f"{len(batch.metrics)} metric(s); at least 8 are required. "
            f"Missing required roles: {', '.join(missing_roles) or '<none>'}."
        )

    # Identity always comes from EDGAR, never from the model.
    company = state.get("company_name") or batch.company_name
    apply_extractor_agreement(batch.metrics, agreement)
    attach_evidence_context(
        batch.metrics,
        state.get("tables_markdown"),
        state.get("filing_metadata") or {},
    )
    attach_cross_statement(
        batch.metrics,
        state.get("tables_markdown"),
        state.get("filing_metadata") or {},
    )
    metrics = [
        normalize_metric_dict(metric.model_dump(mode="json"))
        for metric in batch.metrics
    ]
    return {
        "company_name": company,
        "extracted_metrics": metrics,
        # Keep an immutable copy so the accuracy report can score the original
        # extraction even after a human corrects a value.
        "original_metrics": copy.deepcopy(metrics),
        "status": "EXTRACTED",
    }


def validate_node(state: AuditState) -> dict[str, Any]:
    """Run deterministic validation, explain YoY anomalies, and route."""
    if state.get("validation_checks"):
        return {}

    raw_metrics = state.get("extracted_metrics") or []
    if not raw_metrics:
        raise ValueError("extracted_metrics is empty; extract_node must run first.")

    metrics = [
        metric
        if isinstance(metric, ExtractedMetric)
        else ExtractedMetric.model_validate(metric)
        for metric in raw_metrics
    ]
    checks, flagged = validate_metrics(
        metrics,
        confidence_threshold=float(state.get("confidence_threshold", 0.85)),
        yoy_threshold_pct=float(state.get("yoy_threshold_pct", 30.0)),
        filing_metadata=state.get("filing_metadata") or {},
        tables=state.get("tables_markdown"),
    )

    segment_checks, segment_flags = _segment_checks(state.get("tables_markdown"))
    checks.extend(segment_checks)
    flagged.extend(segment_flags)

    metric_lookup = {_normalize_name(metric.metric_name): metric for metric in metrics}
    explanations: dict[str, str] = {}
    for item in flagged:
        if "YoY Analysis" not in (item.get("rules") or []):
            continue
        metric = metric_lookup.get(_normalize_name(item.get("metric_name", "")))
        if metric is None:
            continue
        explanations[item["metric_name"]] = _explain_anomaly(metric, item)

    routing_decision = _route_with_agent(flagged, explanations)

    return {
        "extracted_metrics": [metric.model_dump(mode="json") for metric in metrics],
        "validation_checks": [check.model_dump(mode="json") for check in checks],
        "flagged_items": flagged,
        "anomaly_explanations": explanations,
        "routing_decision": routing_decision,
        "status": "PAUSED_FOR_REVIEW" if flagged else "VALIDATED",
    }


def _unwrap_decisions(payload: Any) -> dict[str, Any]:
    if payload is None:
        return {}
    if not isinstance(payload, dict):
        raise ValueError("Human review payload must be a decision mapping.")
    nested = payload.get("decisions")
    if isinstance(nested, dict):
        return nested
    return payload


def _is_red_tier(item: dict[str, Any]) -> bool:
    """Return True when a review item requires the explicit red-tier guard."""
    severity = str(item.get("severity") or "").strip().upper()
    return severity in {"FAIL", "HIGH", "RED", "CRITICAL"}


def human_review_node(state: AuditState) -> dict[str, Any]:
    """Pause for human review, then apply and persist every human decision."""
    flagged = state.get("flagged_items") or []
    if not flagged:
        return {"status": "AUTO_APPROVED"}

    payload = {
        "thread_id": state.get("thread_id"),
        "company_name": state.get("company_name"),
        "flagged_items": flagged,
        "anomaly_explanations": state.get("anomaly_explanations") or {},
    }
    # IMPORTANT: LangGraph re-runs this node from the top when the thread is
    # resumed.  No database writes, LLM calls, or HTTP calls may happen before
    # interrupt(); every side effect below is idempotent and runs after it.
    decisions = _unwrap_decisions(interrupt(payload))

    decision_lookup: dict[str, dict[str, Any]] = {}
    for metric_name, entry in decisions.items():
        if isinstance(entry, str):
            entry = {"decision": entry}
        if isinstance(entry, dict):
            decision_lookup[_normalize_name(metric_name)] = entry

    metrics = list(state.get("extracted_metrics") or [])
    records: list[dict[str, Any]] = []
    rejected_names: set[str] = set()

    for item in flagged:
        metric_name = item.get("metric_name") or ""
        normalized = _normalize_name(metric_name)
        entry = decision_lookup.get(normalized)
        if entry is None:
            # A caller may omit an item; leave it unresolved rather than
            # silently approving a flagged metric.
            continue

        decision = str(entry.get("decision") or "").strip().upper()
        if decision not in {"APPROVED", "CORRECTED", "REJECTED"}:
            raise ValueError(
                f"Metric {metric_name!r} has invalid decision {decision!r}; "
                "expected APPROVED, CORRECTED, or REJECTED."
            )
        if (
            decision == "APPROVED"
            and _is_red_tier(item)
            and not bool(entry.get("acknowledge_risk"))
        ):
            raise ValueError(
                f"Metric {metric_name!r} is red-tier ({item.get('severity')}); "
                "approving it requires acknowledge_risk=true after reviewing the "
                "source evidence."
            )

        metric_index = next(
            (
                index
                for index, metric in enumerate(metrics)
                if _normalize_name(metric.get("metric_name", "")) == normalized
            ),
            None,
        )
        original_value = (
            metrics[metric_index].get("original_value")
            if metric_index is not None
            else item.get("value")
        )
        if original_value is None and metric_index is not None:
            original_value = metrics[metric_index].get("value")
            metrics[metric_index]["original_value"] = original_value

        corrected_value: float | None = None
        if decision == "CORRECTED":
            raw_corrected = entry.get("corrected_value")
            if raw_corrected in (None, ""):
                raise ValueError(
                    f"Metric {metric_name!r} was CORRECTED without corrected_value."
                )
            try:
                corrected_value = float(raw_corrected)
            except (TypeError, ValueError) as error:
                raise ValueError(
                    f"Metric {metric_name!r} has a non-numeric corrected_value "
                    f"{raw_corrected!r}."
                ) from error
            if metric_index is not None:
                metrics[metric_index]["value"] = corrected_value
                normalize_metric_dict(metrics[metric_index])
        elif decision == "REJECTED":
            rejected_names.add(normalized)

        reason = "; ".join(item.get("reasons") or []) or "Flagged for human review."
        notes = str(
            entry.get("notes")
            or entry.get("reviewer_notes")
            or ""
        ).strip()

        thread_id = str(state.get("thread_id") or "")
        # INSERT OR IGNORE + the unique idempotency index makes a node replay
        # safe: no duplicate audit rows can be created.
        insert_audit_log(
            thread_id=thread_id,
            company_name=state.get("company_name") or "",
            cik=str(state.get("cik") or ""),
            metric_name=metric_name,
            original_value=float(original_value) if original_value is not None else None,
            corrected_value=corrected_value,
            decision=decision,
            reason=reason,
            reviewer_notes=notes,
        )

        records.append(
            {
                "metric_name": metric_name,
                "original_value": original_value,
                "corrected_value": corrected_value,
                "decision": decision,
                "reason": reason,
                "reviewer_notes": notes,
            }
        )

    if rejected_names:
        metrics = [
            metric
            for metric in metrics
            if _normalize_name(metric.get("metric_name", "")) not in rejected_names
        ]

    return {
        "extracted_metrics": metrics,
        "human_decisions": records,
        "status": "HUMAN_REVIEWED",
    }


_ANOMALY_RULES = {
    "Accounting Equation",
    "YoY Analysis",
    "Segment Validation",
    "Segment Table Check",
}


def _fact_usd(fact: dict[str, Any]) -> float:
    """Return an XBRL fact in full USD (Company Facts are stored in USD)."""
    if fact.get("raw_value") is not None:
        return float(fact["raw_value"])
    return float(fact["value"]) * 1_000_000.0


def _metric_usd(metric: dict[str, Any], *, original: bool = False) -> float | None:
    """Return a serialized metric in full USD, normalizing legacy records."""
    if original and metric.get("original_value") is not None:
        value = metric.get("original_value")
    else:
        value = metric.get("value")
    if value is None:
        return None
    if metric.get("value_usd") is not None and not original:
        return float(metric["value_usd"])
    normalized = normalize_metric_dict(dict(metric))
    if original and normalized.get("original_value") is not None:
        normalized["value"] = normalized["original_value"]
        return float(normalize_metric_dict(normalized).get("value_usd") or 0.0)
    return float(normalized.get("value_usd") or 0.0)


def _build_accuracy_report(
    state: AuditState,
    truth: dict[str, Any],
) -> dict[str, Any]:
    """Score original and final audited values against SEC XBRL facts."""
    metrics = state.get("extracted_metrics") or []
    original_metrics = state.get("original_metrics") or metrics
    truth_by_role = {
        _truth_role(name): fact for name, fact in (truth.get("metrics") or {}).items()
    }
    final_by_name = {
        _normalize_name(metric.get("metric_name", "")): metric for metric in metrics
    }
    checks = state.get("validation_checks") or []

    details: list[dict[str, Any]] = []
    original_matches = 0
    original_comparable = 0
    final_matches = 0
    final_comparable = 0

    for original in original_metrics:
        name = str(original.get("metric_name") or "")
        normalized_name = _normalize_name(name)
        role = _metric_role(name)
        fact = truth_by_role.get(role)
        original_reported = original.get("original_value")
        if original_reported is None:
            original_reported = original.get("value")
        original_usd = _metric_usd(original, original=True)

        final_metric = final_by_name.get(normalized_name)
        audited_reported = (
            final_metric.get("value") if final_metric is not None else None
        )
        audited_usd = _metric_usd(final_metric) if final_metric is not None else None

        if fact is None or original_usd is None:
            details.append(
                {
                    "metric_name": name,
                    "role": role,
                    "original_value": original_reported,
                    "audited_value": audited_reported,
                    "extracted_value": (
                        audited_reported
                        if audited_reported is not None
                        else original_reported
                    ),
                    "xbrl_value": None,
                    "difference": None,
                    "original_difference": None,
                    "match": False,
                    "original_match": None,
                    "final_match": None,
                    "confidence": original.get("confidence_score"),
                    "confidence_label": original.get("confidence_label"),
                    "note": "No XBRL fact available for this metric role (no ground truth).",
                }
            )
            continue

        expected_usd = _fact_usd(fact)
        display_xbrl = round(expected_usd / 1_000_000.0, 6)
        tolerance_usd = max(abs(expected_usd) * (ACCURACY_TOLERANCE_PCT / 100.0), 1.0)
        original_match = abs(original_usd - expected_usd) <= tolerance_usd
        original_comparable += 1
        if original_match:
            original_matches += 1

        final_match: bool | None = None
        if audited_usd is not None:
            final_comparable += 1
            final_match = abs(audited_usd - expected_usd) <= tolerance_usd
            if final_match:
                final_matches += 1

        display_value = (
            audited_reported if audited_reported is not None else original_reported
        )
        display_usd = audited_usd if audited_usd is not None else original_usd
        difference_usd = display_usd - expected_usd
        original_difference_usd = original_usd - expected_usd
        details.append(
            {
                "metric_name": name,
                "role": role,
                "original_value": round(float(original_reported), 6),
                "audited_value": (
                    round(float(audited_reported), 6)
                    if audited_reported is not None
                    else None
                ),
                "extracted_value": (
                    round(float(display_value), 6)
                    if display_value is not None
                    else None
                ),
                "xbrl_value": display_xbrl,
                "original_value_usd": round(original_usd, 6),
                "audited_value_usd": (
                    round(audited_usd, 6) if audited_usd is not None else None
                ),
                "xbrl_value_usd": round(expected_usd, 6),
                "difference": round(difference_usd / 1_000_000.0, 6),
                "difference_usd": round(difference_usd, 6),
                "original_difference": round(
                    original_difference_usd / 1_000_000.0, 6
                ),
                "original_difference_usd": round(original_difference_usd, 6),
                "tolerance": round(tolerance_usd / 1_000_000.0, 6),
                "tolerance_usd": round(tolerance_usd, 6),
                "original_match": original_match,
                "final_match": final_match,
                "match": bool(final_match) if final_match is not None else original_match,
                "confidence": original.get("confidence_score"),
                "confidence_label": original.get("confidence_label"),
            }
        )

    original_accuracy_pct = 0.0
    if original_comparable > 0:
        original_accuracy_pct = round(
            (original_matches / original_comparable) * 100.0, 2
        )
    original_accuracy_pct = max(0.0, min(100.0, original_accuracy_pct))
    
    accuracy_pct = 0.0
    if final_comparable > 0:
        accuracy_pct = round((final_matches / final_comparable) * 100.0, 2)
    accuracy_pct = max(0.0, min(100.0, accuracy_pct))
    final_details = [
        detail for detail in details if detail.get("audited_value") is not None
    ]

    metadata = state.get("filing_metadata") or {}
    logs = get_audit_logs(str(state.get("thread_id") or ""))
    counts = Counter(log["decision"] for log in logs)
    flagged = state.get("flagged_items") or []
    logged_names = {_normalize_name(log["metric_name"]) for log in logs}
    unresolved = [
        item
        for item in flagged
        if _normalize_name(item.get("metric_name", "")) not in logged_names
    ]

    # Attach escalation typing to the per-metric accuracy records so the API
    # and CSV exports can show why each value was reviewed.
    flagged_by_name = {
        _normalize_name(item.get("metric_name", "")): item for item in flagged
    }
    for detail in details:
        item = flagged_by_name.get(_normalize_name(detail["metric_name"]))
        if item is None:
            detail["escalation_types"] = []
            detail["escalation_rules"] = []
            detail["escalation_reasons"] = []
            continue
        detail["escalation_types"] = types_for_item(item)
        detail["escalation_rules"] = list(item.get("rules") or [])
        detail["escalation_reasons"] = list(item.get("reasons") or [])

    per_metric_accuracy = [
        {
            "metric_name": detail["metric_name"],
            "role": detail["role"],
            "original_match": detail.get("original_match"),
            "final_match": detail.get("final_match"),
            "original_difference": detail.get("original_difference"),
            "final_difference": detail.get("difference"),
            "confidence": detail.get("confidence"),
            "escalation_types": detail.get("escalation_types") or [],
        }
        for detail in details
    ]

    # ---- Escalation quality (evaluation criteria) -----------------------
    anomaly_failures: dict[str, set[str]] = {}
    for check in checks:
        if (
            check.get("rule_name") in _ANOMALY_RULES
            and not check.get("passed")
            and check.get("severity") != "SKIPPED"
        ):
            key = _normalize_name(check.get("metric_name", ""))
            anomaly_failures.setdefault(key, set()).add(str(check.get("rule_name")))
    corrected_or_rejected = {
        _normalize_name(log["metric_name"])
        for log in logs
        if log["decision"] in {"CORRECTED", "REJECTED"}
    }

    genuine_issue_names = {
        _normalize_name(detail["metric_name"])
        for detail in details
        if detail.get("original_match") is False
    } | set(anomaly_failures)

    escalated_names: list[str] = []
    for item in flagged:
        key = _normalize_name(item.get("metric_name", ""))
        if key not in escalated_names:
            escalated_names.append(key)
    genuine_escalations = len(set(escalated_names) & genuine_issue_names)

    escalation_by_type: dict[str, dict[str, Any]] = {
        ESCALATION_EXTRACTION_RISK: {
            "escalated_count": 0,
            "genuine_count": 0,
            "precision_pct": None,
        },
        ESCALATION_FINANCIAL_ANOMALY: {
            "escalated_count": 0,
            "genuine_count": 0,
            "precision_pct": None,
        },
    }
    for item in flagged:
        key = _normalize_name(item.get("metric_name", ""))
        is_genuine = key in genuine_issue_names or key in corrected_or_rejected
        for escalation_type in types_for_item(item):
            stats = escalation_by_type.setdefault(
                escalation_type,
                {
                    "escalated_count": 0,
                    "genuine_count": 0,
                    "precision_pct": None,
                },
            )
            stats["escalated_count"] += 1
            if is_genuine:
                stats["genuine_count"] += 1
    for stats in escalation_by_type.values():
        if stats["escalated_count"]:
            stats["precision_pct"] = round(
                (stats["genuine_count"] / stats["escalated_count"]) * 100.0, 2
            )
            stats["precision_pct"] = max(0.0, min(100.0, stats["precision_pct"]))

    escalation_precision_pct = None
    if escalated_names:
        escalation_precision_pct = round(
            (genuine_escalations / len(escalated_names)) * 100.0, 2
        )
        escalation_precision_pct = max(0.0, min(100.0, escalation_precision_pct))
    escalation_recall_pct = 100.0
    if genuine_issue_names:
        escalation_recall_pct = round(
            (len(set(escalated_names) & genuine_issue_names) / len(genuine_issue_names)) * 100.0,
            2,
        )
        escalation_recall_pct = max(0.0, min(100.0, escalation_recall_pct))

    auto_names = {
        _normalize_name(log["metric_name"])
        for log in logs
        if log["decision"] == "AUTO_APPROVED"
    }
    auto_details = [
        detail
        for detail in details
        if _normalize_name(detail["metric_name"]) in auto_names
        and detail.get("xbrl_value_usd") is not None
    ]
    auto_matches = sum(
        1 for detail in auto_details if detail.get("original_match") is True
    )
    auto_approval_accuracy_pct = None
    if auto_details:
        auto_approval_accuracy_pct = round(
            (auto_matches / len(auto_details)) * 100.0, 2
        )
        auto_approval_accuracy_pct = max(0.0, min(100.0, auto_approval_accuracy_pct))
    false_auto_approvals = len(auto_details) - auto_matches
    escalation_rate_pct = None
    if original_metrics:
        escalation_rate_pct = round(
            (len(escalated_names) / len(original_metrics)) * 100.0, 2
        )
        escalation_rate_pct = max(0.0, min(100.0, escalation_rate_pct))

    return {
        "thread_id": state.get("thread_id"),
        "company_name": state.get("company_name"),
        "cik": state.get("cik"),
        "fiscal_year": truth.get("fiscal_year") or metadata.get("fiscal_year"),
        "period_end": truth.get("period_end") or metadata.get("report_date"),
        "tolerance_pct": ACCURACY_TOLERANCE_PCT,
        "total_values": len(original_metrics),
        "metrics_compared": final_comparable,
        "matches": final_matches,
        "accuracy_pct": accuracy_pct,
        "final_accuracy_pct": accuracy_pct,
        "original_metrics_compared": original_comparable,
        "original_matches": original_matches,
        "original_accuracy_pct": original_accuracy_pct,
        "metric_details": final_details,
        "original_metric_details": details,
        "per_metric_accuracy": per_metric_accuracy,
        "auto_approved_count": counts.get("AUTO_APPROVED", 0),
        "escalated_count": len(escalated_names),
        "flagged_item_count": len(flagged),
        "human_reviewed_count": (
            counts.get("APPROVED", 0)
            + counts.get("CORRECTED", 0)
            + counts.get("REJECTED", 0)
        ),
        "approved_count": counts.get("APPROVED", 0),
        "corrected_count": counts.get("CORRECTED", 0),
        "rejected_count": counts.get("REJECTED", 0),
        "escalation_precision_pct": escalation_precision_pct,
        "escalation_precision_by_type": escalation_by_type,
        "escalation_recall_pct": escalation_recall_pct,
        "genuine_escalations": genuine_escalations,
        "genuine_issues": len(genuine_issue_names),
        "auto_approval_accuracy_pct": auto_approval_accuracy_pct,
        "auto_approved_compared": len(auto_details),
        "auto_approved_matches": auto_matches,
        "false_auto_approvals": false_auto_approvals,
        "false_auto_approval_count": false_auto_approvals,
        "escalation_rate_pct": escalation_rate_pct,
        "unresolved_flagged_count": len(unresolved),
        "audit_log_count": len(logs),
        "demo_only": bool(state.get("demo_only")),
        "headline_eligible": not bool(state.get("demo_only")),
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }


def finalize_node(state: AuditState) -> dict[str, Any]:
    """Persist auto-approvals, fetch XBRL truth, and build the final report."""
    thread_id = str(state.get("thread_id") or "")
    company_name = state.get("company_name") or ""
    cik = str(state.get("cik") or "")

    existing_logs = get_audit_logs(thread_id)
    logged_names = {_normalize_name(log["metric_name"]) for log in existing_logs}
    flagged_names = {
        _normalize_name(item.get("metric_name", ""))
        for item in (state.get("flagged_items") or [])
    }

    for metric in state.get("extracted_metrics") or []:
        metric_name = metric.get("metric_name") or ""
        normalized = _normalize_name(metric_name)
        if normalized in logged_names or normalized in flagged_names:
            continue
        insert_audit_log(
            thread_id=thread_id,
            company_name=company_name,
            cik=cik,
            metric_name=metric_name,
            original_value=(
                float(metric["value"]) if metric.get("value") is not None else None
            ),
            corrected_value=None,
            decision="AUTO_APPROVED",
            reason="Passed deterministic validation with no review flags.",
            reviewer_notes="Automatically approved; no human review required.",
        )
        logged_names.add(normalized)

    metadata = state.get("filing_metadata") or {}
    try:
        truth = fetch_xbrl_ground_truth(cik)
        accuracy_report = _build_accuracy_report(state, truth)
    except Exception as error:  # noqa: BLE001 - finalize must still record the audit
        logger.warning("XBRL ground-truth lookup failed for CIK %s: %s", cik, error)
        logs = get_audit_logs(thread_id)
        counts = Counter(log["decision"] for log in logs)
        logged_names = {_normalize_name(log["metric_name"]) for log in logs}
        accuracy_report = {
            "thread_id": thread_id,
            "company_name": company_name,
            "cik": cik,
            "fiscal_year": metadata.get("fiscal_year"),
            "period_end": metadata.get("report_date"),
            "tolerance_pct": ACCURACY_TOLERANCE_PCT,
            "total_values": len(state.get("original_metrics") or state.get("extracted_metrics") or []),
            "metrics_compared": 0,
            "matches": 0,
            "accuracy_pct": None,
            "final_accuracy_pct": None,
            "original_metrics_compared": 0,
            "original_matches": 0,
            "original_accuracy_pct": None,
            "metric_details": [],
            "per_metric_accuracy": [],
            "error": f"{type(error).__name__}: {error}",
            "auto_approved_count": counts.get("AUTO_APPROVED", 0),
            "escalated_count": len(state.get("flagged_items") or []),
            "flagged_item_count": len(state.get("flagged_items") or []),
            "human_reviewed_count": (
                counts.get("APPROVED", 0)
                + counts.get("CORRECTED", 0)
                + counts.get("REJECTED", 0)
            ),
            "approved_count": counts.get("APPROVED", 0),
            "corrected_count": counts.get("CORRECTED", 0),
            "rejected_count": counts.get("REJECTED", 0),
            "escalation_precision_pct": None,
            "escalation_precision_by_type": {
                ESCALATION_EXTRACTION_RISK: {
                    "escalated_count": 0,
                    "genuine_count": 0,
                    "precision_pct": None,
                },
                ESCALATION_FINANCIAL_ANOMALY: {
                    "escalated_count": 0,
                    "genuine_count": 0,
                    "precision_pct": None,
                },
            },
            "escalation_recall_pct": None,
            "genuine_escalations": 0,
            "genuine_issues": 0,
            "auto_approval_accuracy_pct": None,
            "auto_approved_compared": 0,
            "auto_approved_matches": 0,
            "unresolved_flagged_count": sum(
                1
                for item in (state.get("flagged_items") or [])
                if _normalize_name(item.get("metric_name", "")) not in logged_names
            ),
            "audit_log_count": len(logs),
            "demo_only": bool(state.get("demo_only")),
            "headline_eligible": not bool(state.get("demo_only")),
            "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        }

    side_effect_counts = {
        "fetch_edgar": 1 if state.get("tables_markdown") else 0,
        "extract_metrics": 1 if state.get("extracted_metrics") else 0,
        "validate": 1 if state.get("validation_checks") else 0,
        "persist_audit_decisions": 1 if get_audit_logs(thread_id) else 0,
        "fetch_xbrl_truth": 0 if accuracy_report.get("error") else 1,
        "write_accuracy_report": 1 if accuracy_report else 0,
        "finalize": 1,
    }
    accuracy_report["side_effect_counts"] = side_effect_counts
    return {
        "accuracy_report": accuracy_report,
        "side_effect_counts": side_effect_counts,
        "status": "COMPLETED",
    }


