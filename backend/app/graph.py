def _normalize_name(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", str(name).lower()).strip()


def _metric_role(name: str) -> str:
    """Map an extracted metric name to its canonical XBRL comparison role."""
    normalized = _normalize_name(name)
    if "revenue" in normalized or "net sales" in normalized:
        return "Revenue"
    if "net income" in normalized or "net earnings" in normalized or "net loss" in normalized:
        return "Net Income"
    if normalized == "assets" or "total assets" in normalized:
        return "Total Assets"
    if normalized == "liabilities" or "total liabilities" in normalized:
        return "Total Liabilities"
    if (
        "shareholders equity" in normalized
        or "stockholders equity" in normalized
        or normalized == "total equity"
    ):
        return "Shareholders' Equity"
    if (
        "operating cash flow" in normalized
        or "operating activities" in normalized
        or "cash provided by operating" in normalized
        or "cash generated by operating" in normalized
        or "cash from operations" in normalized
    ):
        return "Operating Cash Flow"
    if "cash and cash equivalents" in normalized:
        return "Cash and Cash Equivalents"
    if "research" in normalized and "development" in normalized:
        return "R&D / Operating Income"
    if "operating income" in normalized:
        return "R&D / Operating Income"
    return name


def _truth_role(name: str) -> str:
    if name in {"Research and Development Expense", "Operating Income"}:
        return "R&D / Operating Income"
    return name


def _format_number(value: Any) -> str:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return str(value)
    text = f"{number:,.4f}".rstrip("0").rstrip(".")
    return text or "0"


def _message_text(message: Any) -> str:
    content = getattr(message, "content", message)
    if isinstance(content, list):
        parts: list[str] = []
        for item in content:
            if isinstance(item, str):
                parts.append(item)
            elif isinstance(item, dict) and isinstance(item.get("text"), str):
                parts.append(item["text"])
        content = " ".join(parts)
    return str(content).strip()


def _two_sentences(text: str, fallback_tail: str) -> str:
    """Keep at most two sentences; always return a usable explanation."""
    cleaned = (
        str(text)
        .replace("\u2010", "-")
        .replace("\u2011", "-")
        .replace("\u2013", "-")
        .replace("\u2014", "-")
        .replace("\u2018", "'")
        .replace("\u2019", "'")
        .replace("\u201c", '"')
        .replace("\u201d", '"')
    )
    cleaned = " ".join(cleaned.split())
    if not cleaned:
        return fallback_tail
    parts = [part for part in re.split(r"(?<=[.!?])\s+", cleaned) if part]
    if not parts:
        return fallback_tail
    first = parts[0].rstrip()
    if first[-1:] not in ".!?":
        first += "."
    if len(parts) >= 2:
        second = parts[1].rstrip()
        if second[-1:] not in ".!?":
            second += "."
        return f"{first} {second}"
    return f"{first} {fallback_tail}"


def _render_tables(tables: list[dict[str, Any]] | list[str] | None) -> str:
    sections: list[str] = []
    for index, table in enumerate(tables or [], start=1):
        if isinstance(table, str):
            sections.append(f"### Table {index}\n{table}")
            continue
        title = table.get("title") or f"Table {index}"
        category = table.get("category") or "financial"
        markdown = table.get("markdown") or ""
        sections.append(f"### {title} [{category}]\n{markdown}")
    return "\n\n".join(sections)


def _build_extraction_prompt(state: AuditState) -> str:
    metadata = state.get("filing_metadata") or {}
    company = state.get("company_name") or metadata.get("company_name") or "Unknown company"
    cik = state.get("cik") or metadata.get("cik") or ""
    fiscal_year = metadata.get("fiscal_year") or "the latest fiscal year"
    report_date = metadata.get("report_date") or "the latest period end"
    filing_date = metadata.get("filing_date") or "unknown"
    required = "\n".join(
        f"{index}. {metric}" for index, metric in enumerate(REQUIRED_METRICS, start=1)
    )

    return f"""You are the extraction engine of a financial auditing agent.
Extract the required metrics from the SEC 10-K tables below.

Company: {company}
CIK: {cik}
Fiscal year: {fiscal_year}
Period end: {report_date}
10-K filed: {filing_date}

Required metric_name values (use these exact names):
{required}

Rules:
- Use only the tables below. Do not use outside knowledge or XBRL.
- Identify the column whose header matches the filing fiscal year ({fiscal_year}
  / period end {report_date}). Do not assume it is the first numeric column;
  some filers present years oldest-to-newest.
- value is the current fiscal-year figure from that column.
- prior_year_value is the figure from the column for the immediately prior fiscal year.
- Report both values in USD Millions exactly as shown in the table; do not rescale.
- Values in parentheses are negative; return them as negative numbers.
- Use the consolidated total line, not a product line or a single segment.
- Revenue: use "Revenue" or "Total net sales".
- Operating Cash Flow: use the total from the operating section.
- Cash and Cash Equivalents: use the balance-sheet line, not the cash-flow ending balance.
- If R&D is separately reported, use "Research and Development Expense"; otherwise use
  "Operating Income" for the eighth metric.
- source_snippet must be the exact table row text supporting the current value.
  Copy the row as displayed (pipes may be omitted, but the digits must match).
- confidence must be between 0.0 and 1.0; use 0.95+ only for unambiguous rows.
- Return all eight metrics. Do not omit a metric.

Financial statement tables:
{_render_tables(state.get("tables_markdown"))}
"""


def _numeric_cells(markdown: str) -> tuple[int, int]:
    """Return ``(numeric_cell_count, rows_with_numbers)`` for a markdown table."""
    numeric_count = 0
    numeric_rows = 0
    for line in markdown.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|") or "---" in stripped:
            continue
        cells = [cell.strip() for cell in stripped.strip("|").split("|")]
        row_has_number = False
        for cell in cells:
            cleaned = (
                cell.replace("$", "")
                .replace(",", "")
                .replace("%", "")
                .replace("(", "")
                .replace(")", "")
                .replace("−", "-")
                .strip()
            )
            if re.fullmatch(r"-?\d+(?:\.\d+)?", cleaned):
                numeric_count += 1
                row_has_number = True
        if row_has_number:
            numeric_rows += 1
    return numeric_count, numeric_rows


def _segment_checks(
    tables: list[dict[str, Any]] | None,
) -> tuple[list[ValidationCheck], list[dict[str, Any]]]:
    """Validate segment tables when present; record SKIPPED when absent."""
    checks: list[ValidationCheck] = []
    flagged: list[dict[str, Any]] = []
    segment_tables = [
        table
        for table in (tables or [])
        if isinstance(table, dict) and table.get("category") == "segment"
    ]

    if not segment_tables:
        checks.append(
            ValidationCheck(
                rule_name="Segment Validation",
                metric_name="Segment Information",
                passed=False,
                severity="SKIPPED",
                reason=(
                    "No segment tables were found in the filing; segment validation "
                    "was skipped rather than marked as passed."
                ),
                details={"segment_tables": 0},
            )
        )
        return checks, flagged

    for table in segment_tables:
        title = table.get("title") or "Segment Information"
        numeric_count, numeric_rows = _numeric_cells(table.get("markdown") or "")
        details = {
            "numeric_cells": numeric_count,
            "numeric_rows": numeric_rows,
            "minimum_rows": 2,
        }
        if numeric_count == 0 or numeric_rows < 2:
            reason = (
                f"Segment table contains {numeric_count} numeric cells across "
                f"{numeric_rows} rows; expected at least two populated data rows."
            )
            checks.append(
                ValidationCheck(
                    rule_name="Segment Validation",
                    metric_name=title,
                    passed=False,
                    severity="WARNING",
                    reason=reason,
                    details=details,
                )
            )
            flagged.append(
                {
                    "metric_name": title,
                    "value": None,
                    "unit": None,
                    "period": None,
                    "severity": "WARNING",
                    "rules": ["Segment Validation"],
                    "reasons": [reason],
                    "confidence": None,
                    "llm_confidence": None,
                    "confidence_label": None,
                    "confidence_signals": {},
                    "source_snippet": None,
                    "details": {"Segment Validation": details},
                    "escalation_types": ["FINANCIAL_ANOMALY"],
                }
            )
        else:
            checks.append(
                ValidationCheck(
                    rule_name="Segment Validation",
                    metric_name=title,
                    passed=True,
                    severity="PASS",
                    reason=(
                        f"Segment table contains {numeric_count} numeric cells "
                        f"across {numeric_rows} data rows."
                    ),
                    details=details,
                )
            )

    return checks, flagged


def _fallback_explanation(metric: ExtractedMetric, item: dict[str, Any]) -> str:
    prior = metric.prior_year_value
    if prior in (None, 0):
        return (
            f"{metric.metric_name} is reported at {_format_number(metric.value)} "
            f"{metric.unit} and was flagged for review. Verify the current-period "
            "income-statement, balance-sheet, or cash-flow line before approval."
        )

    pct_change = (metric.value - prior) / abs(prior) * 100.0
    first = (
        f"{metric.metric_name} moved from {_format_number(prior)} to "
        f"{_format_number(metric.value)} {metric.unit}, a {pct_change:+.2f}% "
        "year-over-year change that exceeds the configured review threshold."
    )
    second = (
        "Verify the current-period income-statement line and the related "
        "cash-flow statement line before approval."
    )
    return f"{first} {second}"


def _explain_anomaly(metric: ExtractedMetric, item: dict[str, Any]) -> str:
    """Describe the numeric change and lines to verify, without guessing causes."""
    prior = metric.prior_year_value
    pct_change = (
        (metric.value - prior) / abs(prior) * 100.0
        if prior not in (None, 0)
        else None
    )
    reasons = "; ".join(item.get("reasons") or [])
    prompt = f"""You are a financial anomaly explainer. Describe only the numeric
change in exactly two concise sentences. Do not use bullets.

Metric: {metric.metric_name}
Current value: {_format_number(metric.value)} {metric.unit}
Prior-year value: {_format_number(prior) if prior is not None else 'not available'}
Year-over-year change: {f'{pct_change:+.2f}%' if pct_change is not None else 'not available'}
Validation reasons: {reasons}

Rules:
- State the current value, prior value, and percentage change.
- Name the specific income-statement, balance-sheet, or cash-flow lines the
  reviewer should verify for this metric.
- Do not speculate about causes, drivers, business reasons, macroeconomic
  factors, one-time events, or management intent.
- Do not add facts that are not present in the values or validation reasons.
- Never claim the explanation is verified."""

    try:
        text = _message_text(get_client("anomaly_explainer").invoke(prompt))
        if text:
            return _two_sentences(text, _fallback_explanation(metric, item))
    except Exception as error:  # noqa: BLE001 - optional provider must not break the graph
        logger.info("Anomaly explainer unavailable; using deterministic fallback: %s", error)

    return _fallback_explanation(metric, item)


def _route_with_agent(flagged: list[dict[str, Any]], explanations: dict[str, str]) -> str:
    """Ask the router for ESCALATE/AUTO_APPROVE, then enforce the safe rule."""
    prompt = f"""You are the routing agent for a financial filing audit.
Decide whether this filing needs human review.

Flagged items: {len(flagged)}
Explanations: {explanations}

Return exactly one token: ESCALATE if any item needs human review, otherwise
AUTO_APPROVE."""

    decision = "ESCALATE" if flagged else "AUTO_APPROVE"
    try:
        text = _message_text(get_client("agent_router").invoke(prompt)).upper()
        if "AUTO_APPROVE" in text or "AUTO APPROVE" in text:
            decision = "AUTO_APPROVE"
        elif "ESCALATE" in text:
            decision = "ESCALATE"
    except Exception as error:  # noqa: BLE001 - router is advisory, not a blocker
        logger.info("Router unavailable; using deterministic decision: %s", error)

    # Never auto-approve a filing with validation flags.
    if flagged:
        decision = "ESCALATE"
    return decision


